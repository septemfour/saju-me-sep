// 화면에 입력한 정보를 Gemini에게 보낼 "질문 문장"으로 만듭니다
export function buildSajuUserPrompt({
  name,
  birthDate,
  birthTime,
  gender,
  calendarType,
  age,
}) {
  const genderKo = gender === 'male' ? '남자' : gender === 'female' ? '여자' : '미입력'
  const calendarKo = calendarType === 'lunar' ? '음력' : '양력'

  return `
질문: 사주를 통해 이 사람의 전반적인 성격, 기질, 재능을 분석해 주세요.

이름: ${name || '미입력'}
성별: ${gender || '미입력'} (${genderKo})
나이: ${age != null ? `만 ${age}세` : '미상'}
생년월일: ${birthDate || '미입력'}
태어난 시간: ${birthTime || '미입력'}
달력: ${calendarKo}

위 정보를 바탕으로 사주 명식을 구성하고, 성격·기질·재능을 분석해 주세요.
`.trim()
}
